/**
 * @file debug_config.h
 * @brief 调试打印开关集中管理（阶段 1 验收整改：报告 §2.3 T-14）
 *
 * 背景：原实现在**周期性路径**上留有大量 printf（各传感器 1Hz 打印原始值、
 * MQ 标定状态机 1Hz 打印 Rs/R0、OLED 每次刷新打印一次……）。
 * 虽然 retarget 已改为环形缓冲 + DMA（不再阻塞主循环），但这些打印：
 *   - 占用串口带宽（115200 下约 6%），会干扰后续要接的协议抓包
 *   - 让"结构化输出"（app_uart 的那一帧）失去唯一性 —— 人要看的数据淹没在
 *     调试噪声里
 *
 * 所以把"周期性的调试打印"统一收到本文件的开关后面：默认关闭，
 * **一次性事件**（状态跳转、标定完成、告警触发、故障计数）的打印不受影响 ——
 * 那些信息密度高、频率低，正是应该保留的。
 *
 * 需要排查某个传感器时，把对应开关改成 1 重新编译即可。
 *
 * 来源：本工程新建（阶段 1 验收整改）
 */
#ifndef DEBUG_CONFIG_H
#define DEBUG_CONFIG_H

/* ════════════════════════════════════════════════════
 *  周期性调试打印（默认全关）
 * ════════════════════════════════════════════════════ */

/** 各传感器每次采样的原始值打印（ADC raw / mV / 百分比），约 1Hz 各一行 */
#define DBG_SENSOR_PERIODIC     1

/** MQ 标定状态机的每次迭代打印（含 READY 状态下每秒打印 Rs/R0 与浓度） */
#define DBG_MQ_STATE            1

/* ════════════════════════════════════════════════════
 *  始终保留的打印（无需开关，说明用途以便将来不被误删）
 * ════════════════════════════════════════════════════ */
/*
 * - app_uart 的 "=== DATA ===" 结构化帧（1Hz）：这是设计上的唯一数据出口
 * - app_scheduler 的 [HB] 心跳（5s）与 [STAT] 任务耗时表（60s）
 * - MQ 标定的状态跳转（warmup done / aging done / R0 calibrated / R0 saved|restored）
 * - PIR 状态变化、灌溉动作与告警、BMP280 初始化结果、EEPROM/看门狗初始化结果
 * - 崩溃点追踪与复位原因
 */

#endif /* DEBUG_CONFIG_H */
